const express = require("express");
const cors = require("cors");
const path = require("path");
require("dotenv").config({
    path: path.join(__dirname, "../.env")
});

const OpenAI = require("openai");

const app = express();
const PORT = process.env.PORT || 3000;


// ======================================================
// НАСТРОЙКИ
// ======================================================

app.use(cors());
app.use(express.json({ limit: "1mb" }));


// ======================================================
// OPENAI
// ======================================================

const openai = new OpenAI({
    apiKey: process.env.OPENAI_API_KEY
});


// ======================================================
// ПРОВЕРКА СЕРВЕРА
// ======================================================

app.get("/", (req, res) => {

    res.json({
        success: true,
        message: "QANAT AI Server работает"
    });

});


// ======================================================
// AI АНАЛИЗ
// ======================================================

app.post("/api/analyze", async (req, res) => {

    try {

        if (!process.env.OPENAI_API_KEY) {

            return res.status(500).json({
                error: "OPENAI_API_KEY не найден в .env"
            });

        }


        const { decisions, result } = req.body;


        if (!result) {

            return res.status(400).json({
                error: "Нет результатов симуляции."
            });

        }


        // --------------------------------------------------
        // Формируем данные выбранных решений
        // --------------------------------------------------

        const decisionsText = Array.isArray(decisions)
            ? decisions.map((item, index) => {

                return `
${index + 1}. ${item.id} — ${item.name}
Категория: ${item.category}
Район: ${item.district}
Стоимость: ${item.cost}
`;

            }).join("\n")
            : "Нет данных";


        // --------------------------------------------------
        // Формируем данные районов
        // --------------------------------------------------

        const districtsText = result.districts
            ? Object.entries(result.districts)
                .map(([id, district]) => {

                    return `
${district.name || id}:
Новый балл: ${district.newScore}
`;

                })
                .join("\n")
            : "Нет данных";


        // --------------------------------------------------
        // PROMPT
        // --------------------------------------------------

        const prompt = `
Ты — аналитический помощник городского симулятора QANAT.

Пользователь играет роль акима города Астана.
Он выбирает управленческие решения для районов города.

Твоя задача — проанализировать результат симуляции.

ВАЖНО:
- используй только переданные данные;
- не придумывай отсутствующие показатели;
- объясняй понятно и кратко;
- отвечай на русском языке;
- оцени последствия выбранных решений;
- укажи сильные и слабые стороны стратегии;
- предложи, что можно улучшить.

========================================
ВЫБРАННЫЕ РЕШЕНИЯ
========================================

${decisionsText}

========================================
РЕЗУЛЬТАТ СИМУЛЯЦИИ
========================================

Начальный Score:
${result.baseScore}

Итоговый Score:
${result.finalScore}

Изменение:
${result.improvement}

Средний показатель города:
${result.cityAverage}

Балл слабейшего района:
${result.weakestDistrictScore}

Количество критических показателей:
${result.criticalCount}

========================================
РАЙОНЫ
========================================

${districtsText}

========================================

Сформируй ответ в следующем формате:

1. Общая оценка результата
2. Что было сделано хорошо
3. Какие решения оказались наиболее полезными
4. Какие проблемы остались
5. Что можно было сделать лучше
6. Краткая рекомендация игроку

Не выдумывай данные, которых нет в результатах симуляции.
`;


        // --------------------------------------------------
        // OPENAI REQUEST
        // --------------------------------------------------

        const response = await openai.responses.create({

            model: "gpt-5.6-luna",

            input: prompt

        });


        const analysis = response.output_text;


        if (!analysis) {

            throw new Error(
                "OpenAI вернул пустой ответ."
            );

        }


        // --------------------------------------------------
        // ОТВЕТ БРАУЗЕРУ
        // --------------------------------------------------

        res.json({

            success: true,

            analysis: analysis

        });


    } catch (error) {

        console.error(
            "Ошибка OpenAI:",
            error
        );


        res.status(500).json({

            success: false,

            error:
                error?.message ||
                "Не удалось выполнить AI-анализ."

        });

    }

});


// ======================================================
// ЗАПУСК
// ======================================================

app.listen(PORT, () => {

    console.log("");
    console.log("==============================");
    console.log(" QANAT AI SERVER");
    console.log("==============================");
    console.log(` Server: http://localhost:${PORT}`);
    console.log(` AI:     http://localhost:${PORT}/api/analyze`);
    console.log("==============================");
    console.log("");

});